"""Profile data/raw/*.json and write docs/DATA_PROFILE.md (PRD §10 M0).

Reports per file: record count, field types, None/empty counts, ADVERTISEMENT frequency,
approximate invalid count (PRD §4.3, header detection is a rough heuristic here),
n_steps distribution (newline rule §4.4), and the top 300 crudely-cleaned ingredient names.
Stdlib only; the real normalizer arrives in M1.
"""
import json
import re
import statistics
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "DATA_PROFILE.md"
QTY = re.compile(r"^[\d\s/.\-½¼¾⅓⅔⅛]+")
UNITS = re.compile(r"^(cups?|tablespoons?|teaspoons?|tbsp|tsp|ounces?|oz|pounds?|lbs?|lb|grams?|g|kg|ml|l|pinch|dash|cloves?|cans?|packages?|slices?|sticks?)\b\.?\s*(of\s+)?")


def strip_ad(line: str) -> str:
    """Remove the ADVERTISEMENT artifact (standalone line or glued to the end of a line)."""
    return line.replace("ADVERTISEMENT", "").strip()


def is_real(line) -> bool:
    """A real ingredient line: non-empty after stripping ADVERTISEMENT, not a 'For the sauce:' header."""
    if not isinstance(line, str):
        return False
    s = strip_ad(line)
    return bool(s) and not s.endswith(":")


def crude_name(line: str) -> str:
    """Very rough ingredient name for the frequency table (qty/unit/parenthetical stripped)."""
    s = re.sub(r"\(.*?\)", "", strip_ad(line).lower()).split(",")[0].strip()
    s = QTY.sub("", s).strip()
    return UNITS.sub("", s).strip()


def steps(instr) -> int:
    """n_steps = non-empty newline-separated segments (PRD §4.4)."""
    return sum(1 for x in instr.split("\n") if x.strip()) if isinstance(instr, str) else 0


def dist(xs: list[int]) -> str:
    """One-line distribution summary."""
    if not xs:
        return "n/a"
    q = statistics.quantiles(xs, n=20) if len(xs) > 1 else [xs[0]] * 19
    one = sum(1 for x in xs if x == 1) / len(xs)
    return (f"mean {statistics.mean(xs):.1f}, median {statistics.median(xs)}, p5 {q[0]:.0f}, "
            f"p95 {q[18]:.0f}, max {max(xs)}, share with exactly 1 step {one:.1%}")


def main() -> None:
    """Scan all files, print and write the report."""
    L = ["# DATA_PROFILE", "", "Generated by `python scripts/profile_data.py`. Do not hand-edit.", ""]
    names, total, valid_total, seen_keys, dup_keys = Counter(), 0, 0, set(), 0
    for p in sorted(RAW.glob("*.json")):
        data = json.loads(p.read_text(encoding="utf-8"))
        dup_keys += len(seen_keys & data.keys())
        seen_keys |= data.keys()
        recs = list(data.values())
        keys = list(data)
        ftypes, nones = Counter(), Counter()
        ad_lines = ad_alone = ad_recipes = real_lines = valid = 0
        ing_counts, step_counts = [], []
        for r in recs:
            for f, v in r.items():
                ftypes[(f, type(v).__name__)] += 1
                if v is None or v == "" or v == []:
                    nones[f] += 1
            ing = r.get("ingredients") if isinstance(r.get("ingredients"), list) else []
            ads = sum(1 for x in ing if isinstance(x, str) and "ADVERTISEMENT" in x)
            ad_lines += ads
            ad_alone += sum(1 for x in ing if x == "ADVERTISEMENT")
            ad_recipes += bool(ads)
            real = [x for x in ing if is_real(x)]
            real_lines += len(real)
            n_steps = steps(r.get("instructions"))
            if (r.get("title") or "").strip() and real and n_steps:
                valid += 1
                ing_counts.append(len(real))
                step_counts.append(n_steps)
            names.update(crude_name(x) for x in real)
        total += len(recs)
        valid_total += valid
        L += [f"## {p.name}", "",
              f"- top-level: {type(data).__name__}; records: **{len(recs):,}**; key example: `{keys[0]}`",
              f"- valid (approx. §4.3): **{valid:,}**; invalid: {len(recs) - valid:,}",
              "- field types: " + ", ".join(f"`{f}`:{t}×{c:,}" for (f, t), c in sorted(ftypes.items())),
              "- None/empty per field: " + (", ".join(f"`{f}`×{c:,}" for f, c in nones.items()) or "none"),
              f"- ADVERTISEMENT: in {ad_lines:,} lines ({ad_alone:,} standalone, rest glued to a real "
              f"line's end) across {ad_recipes:,} recipes",
              f"- n_ingredients (valid): {dist(ing_counts)}",
              f"- n_steps (valid): {dist(step_counts)}", ""]
    L += [f"**Total records: {total:,}; approx. valid: {valid_total:,}**; "
          f"hash keys shared across files: {dup_keys:,} (ids are source-prefixed anyway)", "",
          "## Top 300 crude ingredient names", "",
          "(Crude cleaning only; M1 replaces this with the real normalizer.)", ""]
    L += [f"{i}. {n} ({c:,})" for i, (n, c) in enumerate(names.most_common(300), 1)]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[:40]))
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()

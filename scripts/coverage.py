"""Normalization report over data/recipes.db (PRD 4.5 coverage target, M1).

Prints coverage, top unmapped names, top canonicals, tag counts, paragraph-format count and random
parsed lines per source, and rewrites the "Normalization coverage" section of docs/DATA_PROFILE.md.
A line is "mapped" when every required item on it has a canonical used by >= 5 valid recipes.
Usage: python scripts/coverage.py [--samples 5] [--seed 0]
"""
import argparse
import json
import random
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
from app.normalize import BROAD, tags_for, synonym  # noqa: E402

DB = ROOT / "data" / "recipes.db"
PROFILE = ROOT / "docs" / "DATA_PROFILE.md"
MARK = "## Normalization coverage"
LINES = """SELECT l.recipe_id, l.line_no, MIN(COALESCE(v.recipe_count, 0) >= 5) AS ok
FROM ingredient_lines l JOIN recipes r ON r.id = l.recipe_id AND r.valid = 1
LEFT JOIN vocab v ON v.canonical = l.canonical
WHERE l.is_header = 0 AND l.is_alt = 0 GROUP BY l.recipe_id, l.line_no"""


def report(con: sqlite3.Connection, samples: int, seed: int) -> list[str]:
    """Build the markdown report lines."""
    q = lambda sql, *a: con.execute(sql, a).fetchall()
    total, ok = q(f"SELECT COUNT(*), SUM(ok) FROM ({LINES})")[0]
    out = [MARK, "", "Generated by `python scripts/coverage.py`. Do not hand-edit.", "",
           f"- **Coverage: {ok / total:.1%}** of {total:,} real ingredient lines in valid recipes map to a "
           f"canonical used by >= 5 valid recipes (target >= 90%, PRD 4.5)"]
    tot = fb = 0  # rows whose canonical came from the vocab suffix fallback, not the name itself
    for clean, can, n in q("SELECT name_clean, canonical, COUNT(*) FROM ingredient_lines l JOIN recipes r "
                           "ON r.id = l.recipe_id AND r.valid = 1 WHERE is_header = 0 AND is_alt = 0 "
                           "AND canonical IS NOT NULL GROUP BY 1, 2"):
        tot, fb = tot + n, fb + n * (synonym(clean) != can)
    out.append(f"- of which via the suffix fallback (`normalize.suffix_match`): {fb / tot:.1%} of item rows "
               f"(so roughly {ok / total - fb / tot:.1%} map by their own name)")
    (n_voc, n5), = q("SELECT COUNT(*), SUM(recipe_count >= 5) FROM vocab")
    out.append(f"- vocab: {n_voc:,} canonicals, {n5:,} with recipe_count >= 5")
    (para, valid), = q("SELECT SUM(is_paragraph_format), COUNT(*) FROM recipes WHERE valid = 1")
    out.append(f"- paragraph-format recipes (1 newline segment, >= 2 sentences): {para:,} of {valid:,} valid")
    for s, n, p in q("SELECT source, COUNT(*), SUM(is_paragraph_format) FROM recipes WHERE valid = 1 GROUP BY source"):
        out.append(f"  - {s}: {p:,} of {n:,}")
    out += ["", "Recipes per tag (valid recipes; level = worst forced choice, `alt` = only in a line with a "
            "tag-free alternative):", "", "| tag | contains | may_contain | alt |", "|---|---|---|---|"]
    rows = q("SELECT t.tag, t.level, COUNT(*) FROM recipe_tags t JOIN recipes r ON r.id = t.recipe_id "
             "AND r.valid = 1 GROUP BY t.tag, t.level")
    by = {}
    for tag, lv, n in rows:
        by.setdefault(tag, {})[lv] = n
    for tag in sorted(by):
        out.append(f"| {tag} | {by[tag].get('contains', 0):,} | {by[tag].get('may_contain', 0):,} | "
                   f"{by[tag].get('alt', 0):,} |")
    out += ["", "Top 30 unmapped names (canonical with < 5 recipes, or nothing parsed), by line count:", ""]
    unm = q("SELECT COALESCE(l.canonical, '<none> ' || lower(l.raw)), COUNT(*) FROM ingredient_lines l "
            "JOIN recipes r ON r.id = l.recipe_id AND r.valid = 1 LEFT JOIN vocab v ON v.canonical = l.canonical "
            "WHERE l.is_header = 0 AND l.is_alt = 0 AND COALESCE(v.recipe_count, 0) < 5 "
            "GROUP BY 1 ORDER BY 2 DESC LIMIT 30")
    out.append("; ".join(f"{c[:60]} ({n})" for c, n in unm))
    out += ["", "Top 10 canonicals by recipe count:", ""]
    out.append("; ".join(f"{c} ({n:,})" for c, n in
                         q("SELECT canonical, recipe_count FROM vocab ORDER BY recipe_count DESC LIMIT 10")))
    out += ["", "Top 15 canonicals in `contains` recipes per tag (canonical whose own tags say contains -> "
            "recipes); 'line scan only' = contains recipes no parsed canonical explains:", ""]
    vocab = [c for c, in q("SELECT canonical FROM vocab")]
    for tag in ("dairy", "egg", "peanut", "gluten", "meat"):
        cans = json.dumps([c for c in vocab if dict(tags_for(c)).get(tag) == "contains"])
        base = ("FROM recipe_tags t JOIN recipes r ON r.id = t.recipe_id AND r.valid = 1 "
                "WHERE t.tag = ? AND t.level = 'contains'")
        top = q("SELECT l.canonical, COUNT(DISTINCT l.recipe_id) FROM ingredient_lines l JOIN recipe_tags t ON "
                "t.recipe_id = l.recipe_id AND t.tag = ? AND t.level = 'contains' JOIN recipes r ON r.id = l.recipe_id "
                "AND r.valid = 1 WHERE l.is_alt = 0 AND l.canonical IN (SELECT value FROM json_each(?)) "
                "GROUP BY 1 ORDER BY 2 DESC LIMIT 15", tag, cans)
        (scan_only,), = q(f"SELECT COUNT(*) {base} AND NOT EXISTS (SELECT 1 FROM ingredient_lines l WHERE "
                          "l.recipe_id = t.recipe_id AND l.canonical IN (SELECT value FROM json_each(?)))", tag, cans)
        out.append(f"- **{tag}**: " + "; ".join(f"{c} {n:,}" for c, n in top) + f" · line scan only: {scan_only:,}")
    out += ["", "Strict vs broad family recipe counts (valid recipes, required items; broad adds the family's "
            "`broad` list in lexicon/families.yaml):", "", "| family | strict | broad |", "|---|---|---|"]
    fam = {}
    for f in ("garlic", "onion", "tomato"):
        b = json.dumps([f, *BROAD[f]])
        sel = ("SELECT DISTINCT l.recipe_id FROM ingredient_lines l JOIN recipes r ON r.id = l.recipe_id AND "
               "r.valid = 1 WHERE l.is_alt = 0 AND ")
        fam[f] = ({r for r, in q(sel + "l.family = ?", f)},
                  {r for r, in q(sel + "(l.family IN (SELECT value FROM json_each(?)) OR "
                                 "l.canonical IN (SELECT value FROM json_each(?)))", b, b)})
    fam["garlic AND onion"] = tuple(fam["garlic"][i] & fam["onion"][i] for i in (0, 1))
    for f in ("garlic", "onion", "garlic AND onion", "tomato"):
        out.append(f"| {f} | {len(fam[f][0]):,} | {len(fam[f][1]):,} |")
    rnd = random.Random(seed)
    out += ["", f"{samples} random parsed lines per source (raw -> canonical | family | qty unit | tags):", ""]
    for (src,) in q("SELECT DISTINCT source FROM recipes ORDER BY 1"):
        rows = q("SELECT l.raw, l.canonical, l.family, l.qty, l.unit, l.name_clean, l.is_alt FROM ingredient_lines l "
                 "WHERE l.recipe_id >= ? AND l.recipe_id < ? AND l.is_header = 0 "
                 "AND l.recipe_id IN (SELECT id FROM recipes WHERE source = ? ORDER BY random() LIMIT 40)",
                 f"{src}:", f"{src};", src)
        for raw, can, fam, qty, unit, clean, alt in rnd.sample(rows, min(samples, len(rows))):
            tags = ",".join(f"{t}:{lv}" for t, lv in tags_for(synonym(clean))) if clean else ""
            out.append(f"- `{src}` {raw[:70]!r} -> **{can}** | {fam} | {qty if qty is None else round(qty, 2)} "
                       f"{unit or ''} | {tags or '-'}{' (alternative)' if alt else ''}")
    return out


def main() -> None:
    """Print the report and replace the coverage section of DATA_PROFILE.md."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", type=int, default=5)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    con = sqlite3.connect(f"{DB.as_uri()}?mode=ro", uri=True)
    lines = report(con, a.samples, a.seed)
    print("\n".join(lines))
    text = PROFILE.read_text(encoding="utf-8")
    text = text.split(MARK)[0].rstrip() + "\n\n" + "\n".join(lines) + "\n"
    PROFILE.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
